#!/usr/bin/env python3
"""Render docs/operator/i18n-language-review-state.md from the evidence, never from memory.
Inputs: internal/i18n/messages/_status.json + evidence/i18n/<lang>/{pipeline,verdict,review}.json.
  python3 -I scripts/i18n_review_state.py           rewrite the document
  python3 -I scripts/i18n_review_state.py --check   rc 0 current, 1 stale, 2 inputs missing (never a pass)
Identities are copied verbatim from the evidence files; a missing identity is printed as 'not recorded', never guessed.
'reviewed' in _status.json means: an independent REVIEWER MODEL (different from the translator) recorded a PASS verdict. It does
NOT mean a human native speaker reviewed it; the 'human review' column is 'none recorded' unless an evidence file says otherwise."""
import json, os, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(R, "docs/operator/i18n-language-review-state.md")
def j(p):
    try: return json.load(open(os.path.join(R, p), encoding="utf-8"))
    except Exception: return None
def render():
    st = j("internal/i18n/messages/_status.json")
    if st is None or not os.path.isdir(os.path.join(R, "evidence/i18n")): return None
    langs = sorted(l for l in os.listdir(os.path.join(R, "evidence/i18n")))
    rows = []
    for l in langs:
        p = j("evidence/i18n/%s/pipeline.json" % l) or {}; v = j("evidence/i18n/%s/verdict.json" % l) or {}; r = j("evidence/i18n/%s/review.json" % l) or {}
        if not v: return None
        how = "HelixTranslate pipeline" if "translate-pipeline" in str(p.get("pipeline", "")) else "Claude subagent (operator decision 2026-11-24)" if "claude" in str(v.get("translator", "")) and "cohere" not in str(v.get("translator", "")) else str(p.get("pipeline", "not recorded"))[:60]
        rounds = r.get("round") or r.get("rounds") or "not recorded"
        sc = v.get("scores") or {}
        rows.append("| `%s` | %s | %s | %s | %s | %s | %s | %s | none recorded |" % (
            l, st.get(l, {}).get("state", "en (source)" if l == "en" else "not in _status.json"), how, v.get("translator", "not recorded"),
            v.get("reviewer", "not recorded"), v.get("verdict", "?"), rounds, ", ".join("%s %s" % (k, x) for k, x in sc.items()) or "not recorded"))
    return """# i18n language review state

<!-- generated by scripts/i18n_review_state.py from evidence/i18n/*/ and internal/i18n/messages/_status.json; do not edit by hand -->

State of every shipped UI catalogue, derived from the evidence files. **`reviewed` means an independent reviewer MODEL, different
from the translator, recorded a PASS verdict (section 11.4.256 independence). It does not mean a human native speaker reviewed the
text.** Reviewer and translator identities are copied from the evidence; nothing is inferred. English is the source catalogue.

| lang | _status.json | how translated | translator | reviewer | verdict | review rounds | scores | human native review |
|---|---|---|---|---|---|---|---|---|
%s

Honest notes:
- `de` and `ru` came from the umbrella HelixTranslate pipeline (providers listed in the translator column); every other language was
  translated by a Claude subagent because pipeline output failed independent review there (operator decision 2026-11-24, recorded in
  each `evidence/i18n/<lang>/pipeline.json`). That is a deviation from the 11.4.255 pipeline default, taken by the operator.
- Authority (operator decisions of 2026-11-24, taken by interactive question): (1) the Claude-subagent translation is a ratified
  deviation from the HelixTranslate pipeline, which is why tasks T129 and T132-T142 are ticked; (2) the project's definition of
  "reviewed" is an independent reviewer-model PASS, which is why T143-T156 are ticked only where `verdict.json` is PASS and
  `gates/verify_argorder.sh` is green. Human native review remains a documented optional follow-up.
- A human native-speaker review has NOT been recorded for any language. Until one is, treat every non-English catalogue as
  machine-translated and model-reviewed. Recording a human review means adding a `human_review` object to that language's
  `verdict.json` (name or handle, date); this document will then show it.
- Fonts: `scripts/build_noto_subsets.py --check`; real-browser render: `evidence/i18n-render/` (see tests/e2e/i18n_render_test.go).
""" % "\n".join(rows)
def main():
    s = render()
    if s is None: print("UNDETERMINED: evidence or _status.json missing"); return 2
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if cur != s: print("STALE: docs/operator/i18n-language-review-state.md differs from the evidence"); return 1
        print("OK review-state document matches the evidence"); return 0
    open(OUT, "w", encoding="utf-8").write(s); print("wrote", OUT); return 0
sys.exit(main())
