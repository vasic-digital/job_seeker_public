#!/usr/bin/env python3
"""snapshot_career.py - derive rules/career_snapshot.yaml from the PUBLIC career content (JSK-T049, FR-019).

Usage: CAREER_CONTENT_DIR=<umbrella>/_content/career scripts/snapshot_career.py [--check]
Records the source git commit. --check exits 1 on drift, 2 if the source is unavailable.
"""
import json, os, subprocess, sys
import yaml

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, "rules", "career_snapshot.yaml")
src = os.environ.get("CAREER_CONTENT_DIR", "")
if not src or not os.path.isdir(os.path.join(src, "areas")):
    print("CAREER_CONTENT_DIR unset or has no areas/", file=sys.stderr); sys.exit(2)
areas = {}
for fn in sorted(os.listdir(os.path.join(src, "areas"))):
    if fn.endswith(".yaml"):
        d = yaml.safe_load(open(os.path.join(src, "areas", fn), encoding="utf-8"))
        areas[d["id"]] = list(d["keywords"])
prof = yaml.safe_load(open(os.path.join(src, "profile.yaml"), encoding="utf-8"))
skills = sorted({i for g in prof.get("skills", []) for i in g.get("items", [])})
commit = subprocess.run(["git", "-C", src, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip() or "unknown"
doc = {"schema": "jobseeker.career_snapshot.v1", "source_commit": commit, "areas": areas, "skills": skills}
text = "# generated by scripts/snapshot_career.py; public career content only (FR-019)\n" + \
    yaml.safe_dump(doc, sort_keys=True, allow_unicode=True)
if "--check" in sys.argv:
    cur = yaml.safe_load(open(out, encoding="utf-8"))
    same = cur["areas"] == areas and cur["skills"] == skills
    print("career snapshot drift" if not same else "career snapshot in sync"); sys.exit(0 if same else 1)
open(out, "w", encoding="utf-8").write(text)
print("wrote", out, "areas:", len(areas), "commit:", commit[:12])
