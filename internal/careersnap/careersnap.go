// Package careersnap derives rules/career_snapshot.yaml from the PUBLIC career content (JSK-T049, FR-019).
// Only the public area keywords and profile skill items are read; nothing from the private overlay.
package careersnap

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/goccy/go-yaml"
	"github.com/vasic-digital/job_seeker/internal/yamlsafe"
)

const Schema = "jobseeker.career_snapshot.v1"
const header = "# generated by `jsctl snapshot-career`; public career content only (FR-019)\n"

type Snapshot struct {
	Areas        map[string][]string `yaml:"areas"`
	Schema       string              `yaml:"schema"`
	Skills       []string            `yaml:"skills"`
	SourceCommit string              `yaml:"source_commit"`
}

// Derive reads <dir>/areas/*.yaml and <dir>/profile.yaml. The source commit is `git rev-parse HEAD` of dir,
// or "unknown" when dir is not a git checkout (recorded, never invented).
func Derive(dir string) (*Snapshot, error) {
	files, err := filepath.Glob(filepath.Join(dir, "areas", "*.yaml"))
	if err != nil || len(files) == 0 {
		return nil, fmt.Errorf("careersnap: no areas/*.yaml under the career content dir")
	}
	sort.Strings(files)
	s := &Snapshot{Areas: map[string][]string{}, Schema: Schema, SourceCommit: "unknown"}
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		var a struct {
			ID       string   `yaml:"id"`
			Keywords []string `yaml:"keywords"`
		}
		if err := yamlsafe.Unmarshal(b, &a); err != nil || a.ID == "" {
			return nil, fmt.Errorf("careersnap: %s: not a valid area file", filepath.Base(f))
		}
		s.Areas[a.ID] = a.Keywords
	}
	pb, err := os.ReadFile(filepath.Join(dir, "profile.yaml"))
	if err != nil {
		return nil, err
	}
	var prof struct {
		Skills []struct {
			Items []string `yaml:"items"`
		} `yaml:"skills"`
	}
	if err := yamlsafe.Unmarshal(pb, &prof); err != nil {
		return nil, fmt.Errorf("careersnap: profile.yaml: %w", err)
	}
	seen := map[string]bool{}
	for _, g := range prof.Skills {
		for _, it := range g.Items {
			if !seen[it] {
				seen[it] = true
				s.Skills = append(s.Skills, it)
			}
		}
	}
	sort.Strings(s.Skills)
	if out, err := exec.Command("git", "-C", dir, "rev-parse", "HEAD").Output(); err == nil {
		if c := strings.TrimSpace(string(out)); c != "" {
			s.SourceCommit = c
		}
	}
	return s, nil
}

func (s *Snapshot) Render() ([]byte, error) {
	b, err := yaml.Marshal(s)
	if err != nil {
		return nil, err
	}
	return append([]byte(header), b...), nil
}

// Drift compares the committed snapshot file with a fresh derivation (areas and skills; the source commit
// legitimately moves and is reported separately). It returns human-readable differences, empty when in sync.
func Drift(committedPath string, fresh *Snapshot) ([]string, error) {
	b, err := os.ReadFile(committedPath)
	if err != nil {
		return nil, err
	}
	var cur Snapshot
	if err := yamlsafe.Unmarshal(b, &cur); err != nil {
		return nil, fmt.Errorf("careersnap: committed snapshot unreadable: %w", err)
	}
	var d []string
	ids := map[string]bool{}
	for k := range cur.Areas {
		ids[k] = true
	}
	for k := range fresh.Areas {
		ids[k] = true
	}
	keys := make([]string, 0, len(ids))
	for k := range ids {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		if !equal(cur.Areas[k], fresh.Areas[k]) {
			d = append(d, "area "+k)
		}
	}
	if !equal(cur.Skills, fresh.Skills) {
		d = append(d, "skills")
	}
	return d, nil
}

func equal(a, b []string) bool {
	return bytes.Equal([]byte(strings.Join(a, "\x00")), []byte(strings.Join(b, "\x00")))
}
